"""Export demo data (docs/data.js) and the JS/Python parity fixture from results."""

from __future__ import annotations

import json

import numpy as np

from wildfire.families import FAMILIES
from wildfire.io import ROOT, load_result, results_dir
from wildfire.models import predict_grid
from wildfire.sim import BURNING, BURNT, make_landscapes

DEMO_SEED = 0  # the shipped weights are seed 0, fixed in advance (not the best seed)


def weights_json(p: dict) -> dict:
    return {k: (np.asarray(v, np.float32).astype(float).tolist()) for k, v in p.items()}


def load_weights(fam, kind, seed=DEMO_SEED):
    w = np.load(results_dir() / "weights" / f"{fam}_{kind}_s{seed}.npz")
    return {k: w[k] for k in w.files}


def fixture_state(fam_name, L=12, seed=3):
    rng = np.random.default_rng(seed)
    fam = FAMILIES[fam_name]
    ls = make_landscapes(fam, np.array([0.7]), L, rng)
    st = np.zeros((1, L, L), np.int8)
    u = rng.random((1, L, L))
    st[u < 0.25] = BURNING
    st[(u >= 0.25) & (u < 0.4)] = BURNT
    st[~ls.fuel & (st != 0)] = 0
    return ls, st


def parity_fixture(path=ROOT / "tests" / "fixtures" / "js_parity.json"):
    cases = []
    for fam in ("B", "C"):
        ls, st = fixture_state(fam)
        fields = (ls.fuel, ls.moisture, ls.elevation, ls.wind, ls.s)
        for kind in ("mpnn1", "mpnn2", "structured"):
            p = load_weights(fam, kind)
            pred = predict_grid(kind, p, fields, st)
            cases.append({
                "family": fam, "kind": kind, "L": int(st.shape[1]), "s": float(ls.s[0]),
                "fuel": ls.fuel[0].astype(int).ravel().tolist(),
                "moisture": ls.moisture[0].astype(float).ravel().tolist(),
                "elevation": ls.elevation[0].astype(float).ravel().tolist(),
                "wind": ls.wind[0].astype(float).tolist(), "state": st[0].astype(int).ravel().tolist(),
                "weights": weights_json(p), "expected": pred[0].ravel().tolist(),
            })
    path.write_text(json.dumps({"cases": cases}))


def demo_data(path=ROOT / "docs" / "data.js"):
    S = load_result("summary")["result"]
    fams = {}
    for f, F in S["families"].items():
        gt = load_result(f"ground_truth_{f}")["result"]["L128"]
        models = {}
        for kind in ("mpnn1", "structured"):
            seeds = [{"xc": d["xc"], "w": d["width_10_90"] / (2 * np.log(9))} for d in F["models"][kind]["seeds"]]
            models[kind] = {"seeds": seeds, "mean_xc": F["models"][kind]["xc"]["mean"]}
        fams[f] = {
            "params": FAMILIES[f].to_dict() | {"extra": None},
            "truth": {"xc": gt["xc"], "w": gt["w"],
                      "points": [[x, k / n] for x, k, n in zip(gt["x"], gt["k"], gt["n"], strict=True)]},
            "models": models,
            "weights": {k: weights_json(load_weights(f, k)) for k in ("mpnn1", "structured")},
        }
    from scripts.render import headline

    data = {"headline": headline(S), "families": fams}
    path.write_text("/* Generated by scripts/export_demo.py from results/. Do not edit. */\n"
                    "window.WILDFIRE_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    parity_fixture()
    demo_data()
